# 115/230 那批 C# 迁移模型的真实段形态：53 行 `NAME_I =值 $$` 中间变量 + 别名块，
# 其中夹着一行不带 `$$` 的真实参数（ZRE01_），段外被卡片引用。
_LEGACY_WORK_ATP_WITH_PARAMS = (
    b"BEGIN NEW DATA CASE\r\n"
    b"C Generated by ATPDRAW  \xca\xae\xd2\xbb\xd4\xc2, \xd0\xc7\xc6\xda\xb6\xfe 11, 2025\r\n"
    b"$INCLUDE, D:\\ATP\\115\\ganzi\\fanji\\M123\\short.lib, X0202A, X0202B, X0202C $$\r\n"
    b"$PARAMETER\r\n"
    b"U2I =500 $$\r\n"
    b"ZRE01I =150 $$\r\n"
    b"ZRE01_=ZRE01I\r\n"
    b"RER001=RER001I\r\n"
    b"RELENS____=RELENSI\r\n"
    b"ZRE01_ =ZRE01_\r\n"
    b"BLANK $PARAMETER\r\n"
    b"C card referencing ZRE01_ outside the section\r\n"
)

_LEGACY_WORK_ATP_TAIL_ANCHOR = "RER001=RER001I"


def test_strip_parameter_substitution_matches_csharp_script() -> None:
    """删段逻辑：`$PARAMETER` 到 `RER001=RER001I` 之间只删带 `$$` 的中间变量行。

    不带 `$$` 的参数行是卡片真实引用的参数（ZRE01_），必须保留并按其定义烘成数值，
    硬删会让引擎报未定义变量。
    """
    from app.services.atp_model_format import strip_parameter_substitution

    text = _LEGACY_WORK_ATP_WITH_PARAMS.decode("latin-1")
    new_text, info = strip_parameter_substitution(text)

    assert info["changed"] is True
    assert info["removed_dollar_lines"] == 2          # U2I / ZRE01I
    assert info["kept_names"] == ["ZRE01_"]           # 非 $$ 行烘成数值
    assert "U2I" not in new_text
    assert "ZRE01_=150." in new_text
    # 段外逐字节不变（含 $INCLUDE 行尾的 $$ 与中文注释）
    assert new_text.split(_LEGACY_WORK_ATP_TAIL_ANCHOR, 1)[1] == text.split(_LEGACY_WORK_ATP_TAIL_ANCHOR, 1)[1]


def test_preprocess_legacy_entry_skips_insert_form() -> None:
    """预处理只认旧版形态：$INSERT 新模型的参数段是 7.3 原生形态，不能套同一套锚点。"""
    from app.services.atp_model_format import preprocess_legacy_entry

