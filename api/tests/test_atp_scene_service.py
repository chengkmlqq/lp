def _parse_sample() -> dict:
    return parse_atp_scene(_SAMPLE_ATP, source_file="raoji1/work.atp")


def test_split_card_nodes_recognizes_prefixes():
    assert _split_card_nodes("-1XX0117XX0001  150. 2.5E8") == ("XX0117", "XX0001")
    assert _split_card_nodes("13XXJUE1LINE1A  XX0011 2") == ("XXJUE1", "LINE1A")
    assert _split_card_nodes("14XXSS2A  89814.6239  50.") == ("XXSS2A", None)
    assert _split_card_nodes("99XX0077XX0078  1.57E5") == ("XX0077", "XX0078")
    assert _split_card_nodes("        XX0003              1.E3") == ("XX0003", None)


def test_parse_sample_basic_stats():
    scene = _parse_sample()
    assert scene["schema"] == "lp.atp.scene/1"
    assert scene["source_file"] == "raoji1/work.atp"
    stats = scene["stats"]
    assert stats["branch_count"] == 4  # -1xx、-1xx、XX0003 对地支路、99 非线性卡
    assert stats["switch_count"] == 3
    assert stats["source_count"] == 2
    assert stats["include_count"] == 1
    assert stats["param_count"] == 3


def test_parse_parameters():
    scene = _parse_sample()
    params = {p["name"]: p["value"] for p in scene["parameters"]}
    assert params["RER001"] == "15."
    assert params["RELENS____"] == "1.31"
    assert params["RELE01"] == "24."


