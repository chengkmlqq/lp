def test_parse_real_world_atp_file():
    """用仓库内的真实 work.atp（raoji1，GBK 注释）验证端到端。"""
    real_path = Path(__file__).resolve().parents[1] / "static" / "wine" / "ATP" / "templates" / "raoji1" / "work.atp"
    if not real_path.exists():
        import pytest

        pytest.skip("真实 work.atp 不存在（仓库不完整时跳过）")
    raw = real_path.read_bytes()
    text = None
    for enc in ("utf-8", "gbk"):
        try:
            text = raw.decode(enc)
            break
        except UnicodeDecodeError:
            continue
    assert text is not None
    scene = parse_atp_scene(text, source_file="raoji1/work.atp")
    assert scene["stats"]["node_count"] > 50
    assert scene["stats"]["branch_count"] > 20
    assert scene["stats"]["switch_count"] >= 3
    assert scene["stats"]["source_count"] >= 2
    assert scene["stats"]["include_count"] >= 1


def test_parse_garbage_input_does_not_raise():
    assert parse_atp_scene("")["stats"]["node_count"] == 0
    assert parse_atp_scene("随便乱写的内容\n没有段标记\n")["stats"]["warnings"] >= 0
    assert parse_atp_scene("BEGIN NEW DATA CASE\nnothing at all\n")["stats"]["node_count"] == 0