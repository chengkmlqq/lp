#!/usr/bin/env python3
"""扫描 ATP 模型目录，判定 work.atp 的外部几何引用形态，并核验引用文件是否齐全。

为什么要这个脚本
----------------
ATPDraw 7.2+ 换了 LCC 输出方案，同一套模型可能产出三种形态，LP（本系统）
只对其中一种（$INCLUDE + .lib）支持"按塔变几何"。另两种能跑但几何写死：

  INSERT  : work.atp 里 `$INSERT, ...\\short1.pch`      —— 序号 pch，节点名已烧死
  INCLUDE : work.atp 里 `$INCLUDE, ...\\short.lib, N1,N2` —— lib，节点由引用行注入
  EMBED   : 二者都没有，LCC 结果内嵌在 work.atp 的卡片里 —— 磁盘上没有任何 pch/lib

用法
----
    python scripts/atp_form_scan.py D:\\ATP
    python scripts/atp_form_scan.py D:\\ATP --csv out.csv
    python scripts/atp_form_scan.py "C:\\ATP\\work\\results" --quiet

输出
----
按目录一行：形态 / INSERT 行数 / INCLUDE 行数 / 缺失引用文件 / 头部签名。
退出码恒为 0（这是诊断工具，不是校验闸门）。
"""
from __future__ import annotations

import argparse
import csv
import os
import re
import sys
from collections import Counter
from pathlib import Path

REF_RE = re.compile(r"(?im)^\s*\$(INSERT|INCLUDE)\s*,\s*([^,\s]+)")
SIG_RE = re.compile(r"Generated by (ATPDraw|ATPDRAW)([^\r\n]*?(\d{4}))?")
ENTRY = "work.atp"


def read_text(path: Path) -> str:
    """ATP 文件是 GBK/ANSI 编码，读不了就按 latin-1 兜底（不抛错）。"""
    try:
        return path.read_bytes().decode("gbk", errors="replace")
    except OSError:
        return ""


def classify(text: str) -> tuple[str, list[tuple[str, str]]]:
    """返回 (形态, [(指令, 引用路径)])。"""
    refs = [(m.group(1).upper(), m.group(2)) for m in REF_RE.finditer(text)]
    if not refs:
        return "EMBED", refs
    kinds = {kind for kind, _ in refs}
    if kinds == {"INSERT"}:
        return "INSERT", refs
    if kinds == {"INCLUDE"}:
        return "INCLUDE", refs
    return "MIXED", refs


def missing_refs(base: Path, refs: list[tuple[str, str]]) -> list[str]:
    """引用文件既不在此目录、也不在原绝对路径 → 视为缺失。

    绝对路径按**原样**判断（含 C:\\ 与 D:\\）：这些文件在建模机之外通常不存在，
    正是"拷过来就 Halt"的那类资产。
    """
    out: list[str] = []
    for _, raw in refs:
        name = re.split(r"[\\/]", raw.strip())[-1]
        if not name:
            continue
        if (base / name).is_file():
            continue
        if Path(raw.strip()).is_file():
            continue
        out.append(name)
    return out


def signature(text: str) -> str:
    m = SIG_RE.search(text)
    if not m:
        return "-"
    return f"{m.group(1)} {m.group(3) or ''}".strip()


def scan(root: Path, *, quiet: bool = False) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for base, _dirs, files in os.walk(root):
        lower = {f.lower(): f for f in files}
        if ENTRY not in lower:
            continue
        entry = Path(base) / lower[ENTRY]
        text = read_text(entry)
        form, refs = classify(text)
        ins = sum(1 for k, _ in refs if k == "INSERT")
        inc = sum(1 for k, _ in refs if k == "INCLUDE")
        miss = missing_refs(Path(base), refs)
        numbered = sorted(f for f in lower if re.search(r"\d\.pch$", f))
        pch_all = sorted(f for f in lower if f.endswith(".pch"))
        lib_all = sorted(f for f in lower if f.endswith(".lib"))
        row = {
            "dir": str(Path(base)),
            "form": form,
            "insert": str(ins),
            "include": str(inc),
            "numbered_pch_local": str(len(numbered)),
            "pch_local": str(len(pch_all)),
            "lib_local": str(len(lib_all)),
            "missing": ";".join(miss[:8]),
            "missing_n": str(len(miss)),
            "signature": signature(text),
        }
        rows.append(row)
        if not quiet:
            flag = "OK " if not miss else "MISS"
            print(
                f"{flag} {form:7s} I={ins:2d} N={inc:2d} "
                f"本地序号pch={len(numbered):2d} lib={len(lib_all):2d} "
                f"缺={len(miss):2d} | {Path(base)}",
                file=sys.stdout,
            )
    return rows


def main() -> int:
    ap = argparse.ArgumentParser(description="ATP 模型引用形态扫描（INSERT/INCLUDE/EMBED）")
    ap.add_argument("root", help="要扫描的目录（递归查找 work.atp）")
    ap.add_argument("--csv", help="把明细写到 CSV")
    ap.add_argument("--quiet", action="store_true", help="只打印汇总，不逐目录打印")
    args = ap.parse_args()

    root = Path(args.root)
    if not root.is_dir():
        print(f"目录不存在：{root}", file=sys.stderr)
        return 0

    rows = scan(root, quiet=args.quiet)
    if args.csv and rows:
        with open(args.csv, "w", newline="", encoding="utf-8-sig") as fh:
            writer = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
            writer.writeheader()
            writer.writerows(rows)
        print(f"\n明细已写入 {args.csv}")

    print(f"\n=== 汇总（{len(rows)} 个 work.atp）===")
    for form, n in Counter(r["form"] for r in rows).most_common():
        bad = sum(1 for r in rows if r["form"] == form and r["missing_n"] != "0")
        print(f"  {form:7s} {n:5d} 个，其中引用文件缺失 {bad} 个")
    allbad = [r for r in rows if r["missing_n"] != "0"]
    if allbad:
        print(f"\n缺文件共 {len(allbad)} 个目录，前 10：")
        for r in allbad[:10]:
            print(f"  缺 {r['missing_n']} 个：{r['missing']}  ({r['dir']})")
    print(
        "\n形态含义：INSERT=序号 pch（几何写死，LP 变几何无效）；"
        "INCLUDE=lib（LP 全链路支持）；EMBED=内嵌（无 pch/lib，几何写死）"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
